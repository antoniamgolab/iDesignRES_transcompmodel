"""
Add a graph showing average electricity costs across scenarios to the uncertainty analysis notebook.
"""

import json

# Read the notebook
with open('uncertainty_analysis_results.ipynb', 'r', encoding='utf-8') as f:
    nb = json.load(f)

# Create markdown cell
markdown_cell = {
    "cell_type": "markdown",
    "metadata": {},
    "source": [
        "## Average Electricity Costs by Scenario\n",
        "\n",
        "This section displays the average electricity costs (EUR/kWh) across all geographic locations for each scenario.\n",
        "The electricity prices vary by:\n",
        "- **GENeSYS scenario**: Different scenarios have different base electricity price trajectories\n",
        "- **Charging markup**: 15% or 30% markup applied on top of base prices\n",
        "\n",
        "Formula: `final_price = base_price * genesys_ratio * (1 + charging_markup)`"
    ]
}

# Create code cell for electricity cost visualization
code_cell = {
    "cell_type": "code",
    "execution_count": None,
    "metadata": {},
    "outputs": [],
    "source": [
        "# =============================================================================\n",
        "# AVERAGE ELECTRICITY COSTS BY SCENARIO\n",
        "# =============================================================================\n",
        "\n",
        "import yaml\n",
        "import json\n",
        "import numpy as np\n",
        "import matplotlib.pyplot as plt\n",
        "import pandas as pd\n",
        "from pathlib import Path\n",
        "\n",
        "# Load cases.json\n",
        "with open('input_data/uncertainty_scenarios/cases.json', 'r') as f:\n",
        "    cases_data = json.load(f)\n",
        "\n",
        "cases = {c['case_id']: c for c in cases_data['cases']}\n",
        "\n",
        "# Years to analyze\n",
        "model_years = list(range(2020, 2061))\n",
        "year_indices = [0, 5, 10, 15, 20, 25, 30, 35, 40]  # 2020, 2025, 2030, ..., 2060\n",
        "selected_years = [2020, 2024, 2028, 2032, 2036, 2040, 2044, 2048, 2052, 2056, 2060]\n",
        "\n",
        "# Collect electricity prices for each scenario\n",
        "scenario_prices = {}\n",
        "\n",
        "for i in range(24):\n",
        "    scenario = f'scenario_{i:03d}'\n",
        "    scenario_path = Path(f'input_data/uncertainty_scenarios/{scenario}')\n",
        "    fuel_cost_path = scenario_path / 'FuelCost.yaml'\n",
        "    \n",
        "    if not fuel_cost_path.exists():\n",
        "        print(f'Skipping {scenario}: FuelCost.yaml not found')\n",
        "        continue\n",
        "    \n",
        "    with open(fuel_cost_path, 'r') as f:\n",
        "        fuel_costs = yaml.safe_load(f)\n",
        "    \n",
        "    # Collect electricity prices (average across all locations)\n",
        "    elec_prices_by_year = [[] for _ in range(len(model_years))]\n",
        "    \n",
        "    for entry in fuel_costs:\n",
        "        fuel = entry.get('fuel', '')\n",
        "        if fuel == 'electricity' or fuel == 0 or str(fuel).lower() == 'electricity':\n",
        "            cost_per_kwh = entry.get('cost_per_kWh', [])\n",
        "            if isinstance(cost_per_kwh, list):\n",
        "                for y_idx, price in enumerate(cost_per_kwh):\n",
        "                    if y_idx < len(elec_prices_by_year):\n",
        "                        elec_prices_by_year[y_idx].append(price)\n",
        "    \n",
        "    # Calculate average price per year\n",
        "    avg_prices = []\n",
        "    for y_idx in range(len(model_years)):\n",
        "        if elec_prices_by_year[y_idx]:\n",
        "            avg_prices.append(np.mean(elec_prices_by_year[y_idx]))\n",
        "        else:\n",
        "            avg_prices.append(np.nan)\n",
        "    \n",
        "    case = cases[i]\n",
        "    scenario_prices[i] = {\n",
        "        'genesys': case['genesys_scenario'],\n",
        "        'markup': case['charging_markup'],\n",
        "        'tech_cost': case['tech_cost_multiplier'],\n",
        "        'avg_prices': avg_prices\n",
        "    }\n",
        "\n",
        "print(f'Loaded electricity prices for {len(scenario_prices)} scenarios')\n",
        "\n",
        "# =============================================================================\n",
        "# PLOT 1: Average electricity price trajectory by GENeSYS scenario\n",
        "# =============================================================================\n",
        "\n",
        "fig, axes = plt.subplots(1, 2, figsize=(14, 5))\n",
        "\n",
        "# Color map for GENeSYS scenarios\n",
        "genesys_colors = {\n",
        "    'Go RES': '#e41a1c',\n",
        "    'NECPEssentials': '#377eb8',\n",
        "    'REPowerEU++': '#4daf4a',\n",
        "    'Trinity': '#984ea3'\n",
        "}\n",
        "\n",
        "# Group by GENeSYS and markup\n",
        "ax1 = axes[0]\n",
        "for i, data in scenario_prices.items():\n",
        "    genesys = data['genesys']\n",
        "    markup = data['markup']\n",
        "    color = genesys_colors.get(genesys, 'gray')\n",
        "    linestyle = '-' if markup == 0.15 else '--'\n",
        "    \n",
        "    # Only plot at 4-year intervals (matching model time step)\n",
        "    time_step_years = model_years[::4]  # Every 4 years\n",
        "    time_step_prices = data['avg_prices'][::4]\n",
        "    \n",
        "    label = f\"{genesys} (+{int(markup*100)}%)\"\n",
        "    ax1.plot(time_step_years, time_step_prices, color=color, linestyle=linestyle, \n",
        "             marker='o', markersize=3, label=label, alpha=0.8)\n",
        "\n",
        "ax1.set_xlabel('Year')\n",
        "ax1.set_ylabel('Average Electricity Price (EUR/kWh)')\n",
        "ax1.set_title('Electricity Price Trajectory by Scenario')\n",
        "ax1.legend(bbox_to_anchor=(1.05, 1), loc='upper left', fontsize=8)\n",
        "ax1.grid(True, alpha=0.3)\n",
        "\n",
        "# =============================================================================\n",
        "# PLOT 2: Bar chart of average electricity cost at year 2040\n",
        "# =============================================================================\n",
        "\n",
        "ax2 = axes[1]\n",
        "\n",
        "# Get prices at 2040 (index 20 in model_years)\n",
        "year_2040_idx = 20\n",
        "\n",
        "# Group by GENeSYS and markup\n",
        "bar_data = []\n",
        "for i, data in scenario_prices.items():\n",
        "    bar_data.append({\n",
        "        'scenario_id': i,\n",
        "        'genesys': data['genesys'],\n",
        "        'markup': data['markup'],\n",
        "        'price_2040': data['avg_prices'][year_2040_idx] if year_2040_idx < len(data['avg_prices']) else np.nan\n",
        "    })\n",
        "\n",
        "bar_df = pd.DataFrame(bar_data)\n",
        "\n",
        "# Create grouped bar chart\n",
        "genesys_order = ['Go RES v1.2', 'NECPEssentials v1.2', 'REPowerEU++ v1.2', 'Trinity v1.2']\n",
        "genesys_short = ['Go RES', 'NECP', 'REPower', 'Trinity']\n",
        "x = np.arange(len(genesys_order))\n",
        "width = 0.35\n",
        "\n",
        "prices_15 = [bar_df[(bar_df['genesys'] == g) & (bar_df['markup'] == 0.15)]['price_2040'].mean() \n",
        "             for g in genesys_order]\n",
        "prices_30 = [bar_df[(bar_df['genesys'] == g) & (bar_df['markup'] == 0.30)]['price_2040'].mean() \n",
        "             for g in genesys_order]\n",
        "\n",
        "bars1 = ax2.bar(x - width/2, prices_15, width, label='15% markup', color='steelblue')\n",
        "bars2 = ax2.bar(x + width/2, prices_30, width, label='30% markup', color='darkorange')\n",
        "\n",
        "ax2.set_xlabel('GENeSYS Scenario')\n",
        "ax2.set_ylabel('Average Electricity Price (EUR/kWh)')\n",
        "ax2.set_title('Average Electricity Price at 2040 by Scenario')\n",
        "ax2.set_xticks(x)\n",
        "ax2.set_xticklabels(genesys_short, rotation=15)\n",
        "ax2.legend()\n",
        "ax2.grid(True, alpha=0.3, axis='y')\n",
        "\n",
        "# Add value labels on bars\n",
        "for bars in [bars1, bars2]:\n",
        "    for bar in bars:\n",
        "        height = bar.get_height()\n",
        "        if not np.isnan(height):\n",
        "            ax2.annotate(f'{height:.3f}',\n",
        "                        xy=(bar.get_x() + bar.get_width() / 2, height),\n",
        "                        xytext=(0, 3),\n",
        "                        textcoords=\"offset points\",\n",
        "                        ha='center', va='bottom', fontsize=8)\n",
        "\n",
        "plt.tight_layout()\n",
        "plt.savefig('figures/electricity_prices_by_scenario.pdf', bbox_inches='tight', dpi=150)\n",
        "plt.show()\n",
        "\n",
        "# =============================================================================\n",
        "# Print summary table\n",
        "# =============================================================================\n",
        "\n",
        "print('\\n=== AVERAGE ELECTRICITY PRICES (EUR/kWh) BY SCENARIO AT KEY YEARS ===')\n",
        "print(f'{\"ID\":<4} {\"GENeSYS\":<18} {\"Markup\":<8} {\"2020\":>8} {\"2030\":>8} {\"2040\":>8} {\"2050\":>8} {\"2060\":>8}')\n",
        "print('=' * 80)\n",
        "\n",
        "for i, data in sorted(scenario_prices.items()):\n",
        "    p2020 = data['avg_prices'][0] if len(data['avg_prices']) > 0 else np.nan\n",
        "    p2030 = data['avg_prices'][10] if len(data['avg_prices']) > 10 else np.nan\n",
        "    p2040 = data['avg_prices'][20] if len(data['avg_prices']) > 20 else np.nan\n",
        "    p2050 = data['avg_prices'][30] if len(data['avg_prices']) > 30 else np.nan\n",
        "    p2060 = data['avg_prices'][40] if len(data['avg_prices']) > 40 else np.nan\n",
        "    \n",
        "    print(f'{i:<4} {data[\"genesys\"][:17]:<18} {int(data[\"markup\"]*100):>3}%     '\n",
        "          f'{p2020:>8.4f} {p2030:>8.4f} {p2040:>8.4f} {p2050:>8.4f} {p2060:>8.4f}')"
    ]
}

# Insert cells after cell 3 (paths setup)
insert_position = 4

nb['cells'].insert(insert_position, markdown_cell)
