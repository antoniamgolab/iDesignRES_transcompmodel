"""
YAML Modifier for Uncertainty Analysis
======================================

Applies parameter variations to YAML files AFTER preprocessing.
IMPORTANT: Does NOT modify SM_preprocessing.py or its outputs directly.
Instead, it copies the base case and applies multipliers/adjustments.

Key principle: The base preprocessing values are HOLY - we only apply
transformations on copies.
"""

import yaml
import shutil
from pathlib import Path
from typing import Dict, List, Optional
from dataclasses import dataclass
import copy


@dataclass
class UncertaintyScenario:
    """Imported from parameter_sampler - redefined here for standalone use."""
    scenario_id: int
    electricity_price_multiplier: float
    carbon_price: float
    charging_markup: float
    tech_cost_multiplier: float


class YAMLModifier:
    """
    Applies uncertainty scenario parameters to YAML input files.

    Workflow:
    1. Copy base case folder to new scenario folder
    2. Load relevant YAML files
    3. Apply multipliers/adjustments
    4. Save modified files

    Files modified:
    - FuelCost.yaml: electricity prices (multiplier + markup)
    - GeographicElement.yaml: carbon prices
    - TechVehicle.yaml: BEV capital costs (multiplier)
    """

    def __init__(self, base_case_path: Path, output_base_path: Path):
        """
        Initialize the modifier.

        Parameters:
        -----------
        base_case_path : Path
            Path to the base case input_data folder (generated by SM_preprocessing.py)
        output_base_path : Path
            Path where scenario folders will be created
        """
        self.base_case_path = Path(base_case_path)
        self.output_base_path = Path(output_base_path)

        if not self.base_case_path.exists():
            raise ValueError(f"Base case path does not exist: {self.base_case_path}")

        self.output_base_path.mkdir(parents=True, exist_ok=True)

    def _load_yaml(self, filepath: Path) -> List[Dict]:
        """Load a YAML file."""
        with open(filepath, 'r', encoding='utf-8') as f:
            return yaml.safe_load(f)

    def _save_yaml(self, data: List[Dict], filepath: Path):
        """Save data to YAML file."""
        with open(filepath, 'w', encoding='utf-8') as f:
            yaml.dump(data, f, default_flow_style=False, allow_unicode=True, sort_keys=False)

    def _copy_base_case(self, scenario_id: int) -> Path:
        """
        Copy the base case to a new scenario folder.
        Returns the path to the new scenario folder.
        """
        scenario_folder = self.output_base_path / f"scenario_{scenario_id:03d}"

        if scenario_folder.exists():
            shutil.rmtree(scenario_folder)

        shutil.copytree(self.base_case_path, scenario_folder)
        return scenario_folder

    def _apply_electricity_price_adjustment(
        self,
        scenario_path: Path,
        multiplier: float,
        markup: float
    ):
        """
        Apply electricity price multiplier and markup to FuelCost.yaml.

        New price = base_price * multiplier * (1 + markup)

        Only modifies electricity fuel costs, not diesel.
        """
        fuel_cost_path = scenario_path / "FuelCost.yaml"

        if not fuel_cost_path.exists():
            print(f"  [WARN] FuelCost.yaml not found in {scenario_path}")
            return

        data = self._load_yaml(fuel_cost_path)

        adjustment_factor = multiplier * (1 + markup)

        for entry in data:
            fuel = entry.get('fuel', '')
            if fuel == 'electricity' or fuel == 0:  # Handle both string and id
                cost_per_kwh = entry.get('cost_per_kWh', [])
                if isinstance(cost_per_kwh, list):
                    entry['cost_per_kWh'] = [c * adjustment_factor for c in cost_per_kwh]
                else:
                    entry['cost_per_kWh'] = cost_per_kwh * adjustment_factor

        self._save_yaml(data, fuel_cost_path)
        print(f"  Applied electricity price adjustment: x{adjustment_factor:.3f}")

    def _apply_carbon_price(self, scenario_path: Path, carbon_price: float):
        """
        Apply carbon price to GeographicElement.yaml.

        Carbon price is in EUR/tCO2, stored as a list per year.
        Replaces existing values (which are typically 0).
        """
        geo_element_path = scenario_path / "GeographicElement.yaml"

        if not geo_element_path.exists():
            print(f"  [WARN] GeographicElement.yaml not found in {scenario_path}")
            return

        data = self._load_yaml(geo_element_path)

        for entry in data:
            if 'carbon_price' in entry:
                # Get the length of the existing carbon_price array
                n_years = len(entry['carbon_price'])
                # Replace with new carbon price for all years
                entry['carbon_price'] = [carbon_price] * n_years

        self._save_yaml(data, geo_element_path)
        print(f"  Applied carbon price: {carbon_price:.1f} EUR/tCO2")

    def _apply_tech_cost_multiplier(self, scenario_path: Path, multiplier: float):
        """
        Apply technology cost multiplier to TechVehicle.yaml.

        Only modifies BEV-related vehicles (technology containing 'bev' or 'electric').
        Affects capital_cost field.
        """
        tech_vehicle_path = scenario_path / "TechVehicle.yaml"

        if not tech_vehicle_path.exists():
            print(f"  [WARN] TechVehicle.yaml not found in {scenario_path}")
            return

        data = self._load_yaml(tech_vehicle_path)

        modified_count = 0
        for entry in data:
            # Check if this is a BEV by looking at technology or name
            tech_id = entry.get('technology', -1)
            name = entry.get('name', '').lower()

            # Assuming BEV has technology id = 0 or name contains 'bev'/'electric'
            is_bev = (tech_id == 0) or ('bev' in name) or ('electric' in name)

            if is_bev and 'capital_cost' in entry:
                capital_cost = entry['capital_cost']
                if isinstance(capital_cost, list):
                    entry['capital_cost'] = [c * multiplier for c in capital_cost]
                else:
                    entry['capital_cost'] = capital_cost * multiplier
                modified_count += 1

        self._save_yaml(data, tech_vehicle_path)
        print(f"  Applied tech cost multiplier x{multiplier:.3f} to {modified_count} BEV entries")

    def apply_scenario(self, scenario: UncertaintyScenario) -> Path:
        """
        Apply a complete uncertainty scenario to create a new input folder.

        Parameters:
        -----------
        scenario : UncertaintyScenario
            The scenario with parameter values to apply

        Returns:
        --------
        Path : Path to the created scenario folder
        """
        print(f"\n=== Applying Scenario {scenario.scenario_id} ===")
        print(f"  electricity_price_multiplier: {scenario.electricity_price_multiplier:.3f}")
        print(f"  carbon_price: {scenario.carbon_price:.1f} EUR/tCO2")
        print(f"  charging_markup: {scenario.charging_markup:.1%}")
        print(f"  tech_cost_multiplier: {scenario.tech_cost_multiplier:.3f}")

        # Step 1: Copy base case
        scenario_path = self._copy_base_case(scenario.scenario_id)
        print(f"  Copied base case to: {scenario_path}")

        # Step 2: Apply electricity price adjustment
        self._apply_electricity_price_adjustment(
            scenario_path,
            scenario.electricity_price_multiplier,
            scenario.charging_markup
        )

        # Step 3: Apply carbon price
        self._apply_carbon_price(scenario_path, scenario.carbon_price)

        # Step 4: Apply tech cost multiplier
        self._apply_tech_cost_multiplier(scenario_path, scenario.tech_cost_multiplier)

        # Save scenario metadata
        self._save_scenario_metadata(scenario_path, scenario)

        print(f"  Scenario {scenario.scenario_id} ready at: {scenario_path}")
        return scenario_path

    def _save_scenario_metadata(self, scenario_path: Path, scenario: UncertaintyScenario):
        """Save scenario parameters as metadata file."""
        metadata = {
            'scenario_id': scenario.scenario_id,
            'parameters': {
                'electricity_price_multiplier': scenario.electricity_price_multiplier,
                'carbon_price': scenario.carbon_price,
                'charging_markup': scenario.charging_markup,
                'tech_cost_multiplier': scenario.tech_cost_multiplier
            },
            'base_case': str(self.base_case_path)
        }

        metadata_path = scenario_path / "scenario_metadata.yaml"
        with open(metadata_path, 'w') as f:
            yaml.dump(metadata, f, default_flow_style=False)

    def apply_all_scenarios(self, scenarios: List[UncertaintyScenario]) -> List[Path]:
        """
        Apply multiple scenarios and return list of created folder paths.
        """
        paths = []
        for scenario in scenarios:
            path = self.apply_scenario(scenario)
            paths.append(path)

        print(f"\n=== Created {len(paths)} scenario folders ===")
        return paths


